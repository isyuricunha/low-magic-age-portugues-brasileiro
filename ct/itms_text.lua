<c=ty>投擲武器：</c>匕首，木棒，短矛，矛，飛鏢，標槍，飛斧，輕型戰錘，三叉矛，手裡劍和捕網屬於投擲武器，使用者可以將他的力量修正值應用在傷害檢定上<z>（除了潑濺武器）。你可以投擲並沒有設計成投擲武器的普通武器（既在表：武器中並沒有標明射程的近戰武器），但這樣做會使人物的攻擊檢定受到-4減值。投擲一件輕武器或單手武器是一個標準動作，而投擲一件雙手武器是一個整輪動作。不論武器型別如何，這樣的攻擊只有在擲出20點時才被認為是重擊威脅，並且在重擊時造成雙倍的傷害。這樣的武器具有10尺的射程</z>。

