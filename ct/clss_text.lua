<h2 c=ty>職業和等級特性</h2>
作為通常規則，兼職角色的能力為角色各職業能力的總和。

<b c=ty>等級：</b>角色等級是角色各職業等級之和，用來決定何時獲得新專長或提升屬性值。

職業等級則是角色在不同職業上的等級。對於單一職業角色而言，角色等級和職業等級是一樣的。

<b c=ty>生命值：</b>提升某職業等級時，按該職業獲得生命值，然後加到之前的生命值上。

<b c=ty>基本攻擊加值：</b>將各職業的不同基本攻擊加值相加。結果值+6以上可進行多次攻擊。

<b c=ty>豁免加值：</b>將各職業的不同豁免加值相加。

<b c=ty>屬性增長：</b>按角色等級獲得屬性值增長，不管各職業等級是多少。

<b c=ty>專長：</b>按角色等級獲得專長，不管各職業等級是多少。

<b c=ty>技能：</b>各職業的本職技能均視為角色的本職技能。

如果某技能是兼職角色任一職業的本職技能，那麼角色等級決定了該技能的最大級數。（本職技能的最大級數為3+角色等級。）

如果某技能不是兼職角色任何職業的本職技能，那麼該技能的最大級數是本職技能最大級數的一半。

<b c=ty>法術：</b>角色從他所有施法者等級中獲得法術，同時保留各職業各自的法術列表。若某法術效果基於施法者的職業等級，則施展此法術時需指明選用哪個職業法術列表。

<b c=ty>職業特性：</b>獲得各職業的職業特性，但同時也遭受各職業的特殊限制。（例外：兼職野蠻人職業的人物不會變成文盲。）

