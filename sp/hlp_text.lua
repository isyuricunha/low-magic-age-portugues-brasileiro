R: Todos los recursos del juego pueden ser editados y reemplazados libremente.
   carpeta gfx: gráficos
   carpeta sfx: música y efectos de sonido
   carpeta text: textos. en para Inglés, cs para Chino, etc.

Puedes descargar otros recursos directamente del <url=http://steamcommunity.com/app/576770/workshop/>Steam Workshop</url>.


<h3>P: ¿No es necesario recargar una ballesta? No está equilibrado si las ballestas pesadas son mejores que los arcos largos tanto en distancia como en daño.</h3>
R: Buena sugerencia. La cuestión es que hacer clic en recargar es molesto, y las advertencias emergentes sobre ataques de oportunidad son peores. Por ello, la acción de recargar se ha quitado junto a la dote Recarga Rápida.

Habrá más dotes que distinguirán los arcos y ballestas en el futuro: los arcos son mejores para disparos rápidos y a múltiples objetivos, mientras que las ballestas hacen un daño mayor y ataques perforantes.


<h3>P: ¿Por qué son las hondas armas a dos manos? Tradicionalmente son armas a una mano.</h3>
R: Sí, son armas de una mano pero requieren de las dos para ser recargadas. Es posible usar la ballesta de mano como típica arma a distancia de una mano.


