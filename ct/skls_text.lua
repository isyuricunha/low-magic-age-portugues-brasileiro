本職技能是職業的本職技能列表中列出的技能；跨職技能則是未列出的。

如果購買一個本職技能，每技能點可以獲得一個級數（即此技能檢定時有+1加值）。

如果購買一個跨職技能，每技能點可以獲得1/2級數。（半個級數不會改善技能檢定，但是兩個1/2級數是一個級數。）

