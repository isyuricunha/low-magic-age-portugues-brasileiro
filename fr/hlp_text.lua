<s b=c:ty><b>Le coeur de la mécanique:</b> Dés que vous tentez une action, celle-ci a une chance d'échouer, vous lancez un dé à 20 faces (d20).

Pour déterminer si votre personnage réussit une tâche, procédez comme suit :
• Lancez un d20.
• Ajoutez tous les modificateurs pertinents.
• Comparez le résultat à un nombre cible.

Si le résultat est égal ou supérieur au nombre cible, votre personnage réussit.

Si le résultat est inférieur au nombre cible, vous échouez. 


<b>Dice:</b> Les lancers de dés sont décrits par des expressions telles que « 3d4+3 », qui signifie « lancer trois dés à quatre faces et ajouter 3 » (ce qui donne un nombre compris entre 6 et 15).

Le premier nombre vous indique le nombre de dés à lancer (en additionnant les résultats).

Le nombre immédiatement après le « d » vous indique le type de dé à utiliser.

Tout nombre après cela indique une quantité qui est ajoutée ou soustraite du résultat.


<b>d%:</b> Les dés de centile fonctionnent un peu différemment.

Vous générez un nombre entre 1 et 100 en lançant deux dés différents à dix faces.

L'un (désigné avant que vous ne rouliez) est le chiffre des dizaines. L'autre est le chiffre des uns.

Deux 0 représentent 100. 


<b>Arrondir les fractions:</b> En général, si vous vous retrouvez avec une fraction, arrondissez à l'inférieur, même si la fraction est la moitié ou plus.

<b c=tw>Exception:</b> Certains jets, tels que les dégâts et les points de vie, ont un minimum de 1.


<b>Multiplying:</b> Parfois, une règle vous oblige à multiplier un nombre ou un jet de dé.


Tant que vous appliquez un seul multiplicateur, multipliez le nombre normalement.


Lorsque deux multiplicateurs ou plus s'appliquent à une valeur abstraite (comme un modificateur ou un jet de dé), cependant, combinez-les en un seul multiple, chaque multiple supplémentaire ajoutant 1 de moins que sa valeur au premier multiple.

Ainsi, un double (×2) et un double (×2) appliqués au même nombre donnent un triple (×3, car 2 + 1 = 3).


Lors de l'application de multiplicateurs à des valeurs réelles (telles que le poids ou la distance), les règles mathématiques normales s'appliquent à la place.

Une créature dont la taille double (en multipliant ainsi son poids par 8) puis est transformée en pierre (ce qui multiplierait son poids par un facteur d'environ 3) pèse maintenant environ 24 fois la normale, et non 10 fois la normale.

De même, une créature aveuglée essayant de négocier un terrain difficile compterait chaque case comme 4 cases (en doublant le coût deux fois, pour un multiplicateur total de ×4), plutôt que comme 3 cases (en ajoutant 100 % deux fois).
]]


