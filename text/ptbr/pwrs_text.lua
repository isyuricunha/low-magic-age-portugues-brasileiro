-- Abbreviate long feat names for Western Europe languages (English, French, Italiano...), no need for Chinese and Japanese
function	abbr_pwrs(t)
	for k, v in pairs(t) do
		mk_abbr(v, "Proficiência em Arma", "WP")
		mk_abbr(v, "Proficiência em Escudo", "SP")
		mk_abbr(v, "Proficiência em Armadura", "AP")
		mk_abbr(v, "Duas--Lâminas", "TB")-- must 2 '-'
		mk_abbr(v, "Machado Duplo", "Machado-D")
		mk_abbr(v, "Martelo Gancho de Gnomo", "Gn. M-Martelo")
		mk_abbr(v, "Duplo--Arma", "TW")
		mk_abbr(v, "Duplo--Arma de duas mãos", "TH")
		mk_abbr(v, "Manobras de Combate", "CM")
		mk_abbr(v, "Foco de Perícia", "SF")

		mk_abbr(v, "Anão", "An.")
		mk_abbr(v, "Proficiência", "Prof.")
		mk_abbr(v, "Especialização", "Esp.")
		mk_abbr(v, "Crítico", "Crit.")
		mk_abbr(v, "Equipamento", "Eqpt.")
		mk_abbr(v, "Maravilhoso", "Mar.")

		mk_abbr(v, "Aprimorado ", "Apm. ")
		mk_abbr(v, "Maior ", "Maior ")
		mk_abbr(v, "Perfeito ", "Pft. ")

	--	print(v.a)
	end
end

