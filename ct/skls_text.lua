技能修正 = 技能級數 + 屬性修正 + 雜項修正。

該投擲結果類似攻擊檢定或者豁免判定，投擲結果越高越好。

無論你是試著達到或超過某個特定難度等級（DC），或者要擊敗其他人物的技能檢定結果都是如此。


