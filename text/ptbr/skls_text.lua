Se o resultado × o CD for igual ao dobro ou triplo do preço do item em peças de prata, então você completou a tarefa em metade ou um terço do tempo.

Outros múltiplos do CD reduzem o tempo da mesma forma.

Se o resultado × o CD não for igual ao preço, isso representa o progresso que você fez nesta semana. Registre o resultado e faça um novo teste de Artesanato para a próxima semana. Cada semana, você avança até que o total alcance o preço do item em peças de prata.

Se você falhar um teste por 4 ou menos, não faz progresso nesta semana.

