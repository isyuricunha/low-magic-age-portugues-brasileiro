<s b=c:ty>Pour une classe particulière d'un personnage, les compétences sont divisées en compétences de classe et compétences interclasses.

Les compétences de classe sont les compétences trouvées sur la liste de compétences de classe de votre personnage ; les compétences interclasses sont celles que l'on ne trouve pas.

Si vous achetez une compétence de classe, vous obtenez 1 rang (égal à un bonus de +1 aux tests avec cette compétence) par point de compétence.

Si vous achetez une compétence interclasse, vous obtenez 1/2 rang par point de compétence. (Les demi-rangs n'améliorent pas votre test de compétence, mais deux 1/2 rangs font 1 rang.)

Vous ne pouvez pas économiser de points de compétence pour les dépenser plus tard.

Votre rang maximum dans une compétence de classe est votre niveau de personnage + 3.

Votre rang maximum dans une compétence interclasse est la moitié de ce nombre (n'arrondissez pas à l'entier supérieur ou inférieur).

Qu'une compétence soit achetée en tant que compétence de classe ou interclasse, s'il s'agit d'une compétence de classe pour l'une de vos classes, votre rang maximum est égal au niveau total de votre personnage + 3. 


<b>Utilisation des compétences : </b>Pour effectuer un test de compétence, lancez : 1d20 + modificateur de compétence.

Modificateur de compétence = rang de compétence + modificateur de capacité + modificateurs divers.

Ce jet fonctionne comme un jet d'attaque ou un jet de sauvegarde : plus le jet est élevé, mieux c'est.

Soit vous essayez d'égaler ou de dépasser une certaine classe de difficulté (CD), soit vous essayez de battre le résultat du test d'un autre personnage.


<b>Rangs de compétence : </b> Le nombre de rangs d'un personnage dans une compétence est basé sur le nombre de points de compétence qu'un personnage a investis dans une compétence.

De nombreuses compétences peuvent être utilisées même si le personnage n'a pas de rang ; faire cela s'appelle faire un test de compétence non entraîné.


<b>Modificateur de capacité : </b>Le modificateur de capacité utilisé dans un test de compétence est le modificateur de la capacité clé de la compétence (la capacité associée à l'utilisation de la compétence).

La capacité clé de chaque compétence est notée dans sa description.


<b>Modificateurs divers : </b>Les modificateurs divers incluent les bonus raciaux, les malus aux tests d'armure et les bonus fournis par les dons, entre autres.
