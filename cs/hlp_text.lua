<h3>弩无需装填？！重弩在射程和威力上全面压制了弓，这不科学。

从规则来讲弩是简易武器，弓是军用武器。从游戏来讲，一种武器完全超越另一种武器，那么为啥要用弓？即使射手战士花一点学弩熟练，带来的收益也远超其它技能。

建议取消弩的各种战技，连射对于传统一轮一次的弩本身就不科学。弩狙击保留，可以提供一个强化弩狙击技能，提高威力或提供类似雷电法术的贯穿效果，区分弓和弩的特色。</h3>

早期版本的弩像3r传统一样需要装填（那时“快速装填”专长还未改为“弩狙击”），测试后发现操作太繁琐，很影响战斗节奏；
就又参照灰鹰改为点选敌人装填，发觉还是不爽利；
然后又改为回合开始自动装填，结果在敌人身边时需频频弹借机确认，更烦人！
然后。。。就没有然后了，直接粗暴的将装填砍掉了，造成了现在的不平衡的弩。


不过自然是暂时性的，xvim兄的建议蛮好，可以在配套专长上区分弓和弩：

弓的专长侧重于速射和多点打击；
弩的专长侧重于强力单次打击和贯穿。

如此一来，既用另一种方式保留了弓弩射速差别，又避免了频频装填的繁琐。


<h3>传统上投石索都是单手来着（大卫干歌利亚用的就是这个，单手轮圈然后松手放出去），lma里设定成双手武器是出于平衡性考虑么（单手的话确实有代替弓的可能）？</h3>

投石索是以单手射击，但装填还是要双手，所以还是按双手武器处理。单手远程有一个手弩就够了。

3r：
投石索：你可以将你的力量加值应用于投石索的伤害检定，就像它是投掷武器一样。你可以单手使用投石索射击（但不能单手装填）。装填投石索需要双手，属于移动动作，会引发敌人的借机攻击。

你可以用投石索投掷普通的石头，但是因为石头并没有弹丸质地紧密，也没有那么圆，所以你只能造成比你使用武器尺寸小一级武器的伤害，同时，攻击检定会受到-1的减值。


<h3>为何没有奔跑，佯攻，援助他人等命令？那样系统不是更丰富更好玩吗？</h3>

目前lma侧重点是简洁爽快的战斗，所以暂时舍弃一些传统的玩法，包括pf战技系统也在待定中。

