La dote "Desgarrar con dos armas" funciona con ballestas a dos manos?</h3>
No, no funciona. "Defensa con dos armas", "Defensa Mejorada con dos armas", "Doble Tajo" y "Desgarrar con dos armas" solo funciona con dos armas cuerpo a cuerpo.


<h3>¿Cómo realizar una carga?</h3>
La carga se activa automáticamente cuando se cumplen los prerrequisitos: antes de un ataque cuerpo a cuerpo, movimiento en línea recta desde, al menos, dos casillas de distancia, y con un camino que esté completamente libre de obstáculos y que no encuentre a su paso terreno difícil.


<h3>Encantamiento: Defensa (Solo armas)</h3>
En armas cuerpo a cuerpo podría haber un encantamiento especial: Defensa -+x bonificación de escudo en CA. Funciona de forma similar a un escudo equipado.

Esta bonificación no se acumula con la bonificación de CA de un escudo real, así que es más adecuada para aquellos personajes que utilizan armas a dos manos o dos armas, sin escudos.

Es más complicado si el encantamiento defensivo ocurre en armas que sean tanto cuerpo a cuerpo como arrojadizas, como la jabalina: el encantamiento funciona con normalidad cuando se utiliza como arma cuerpo a cuerpo, pero no tiene efecto si se usa como arma arrojadiza.


<h3>Clérigos y Expulsar a los no-muertos:</h3>
Prueba de expulsión: nivel de personaje + modificador de carisma + bonificaciones de dotes vs. la defensa de Voluntad del objetivo + Resistencia a la Expulsión


<h3>A veces, no hay efecto cuando se lanza un conjuro cuyo objetivo está fuera de la visión.</h3>
El lanzamiento de un conjuro necesita de línea de efecto. Si hay obstáculos no visibles bloqueando la línea de efecto, el conjuro fallará.


<h3>¿Cómo afectan los obstáculos, enemigos y aliados en el campo de batalla?</h3>

Influencias sobre el movimiento:

Los obstáculos y los enemigos no inmovilizados bloquearán tu movimiento. No puedes atravesarlos.

Las casillas adyacentes a enemigos no inmovilizados se denominan como <c=r>Zona de Control (ZoC)</c>, y no puedes atravesarlas. Primero debes moverte a esa casilla y detenerte, esperar a tu próximo turno, y luego continuar el movimiento.

Los enemigos no inmovilizados que tengan equipada un arma cuerpo a cuerpo atacarán a cualquier oponente que intente salir de su ZoC. Este ataque se denomina <c=r>Ataque de Oportunidad (AO)</c>. Cambiar de posición utilizando <c=g>Paso</c> (paso de 1 casilla) puede evitar AOs.

Terreno difícil: terreno con obstáculos menores o con efectos de algunos conjuros (Telaraña, Grasa, etc.), y las casillas ocupadas por aliados o enemigos inmovilizados. Para pasar por este terreno se necesita el doble de esfuerzo, además, no se permite usar <c=g>Paso</c> en ellas.


Influencias sobre el ataque:

Los obstáculos y los enemigos no inmovilizados pueden afectar a tus ataques si el objetivo tiene <c=r>Cobertura</c> (ataque <c=r>-2</c>) o <c=r>Cobertura Total</c> (ataque <c=r>-4</c>); también podrían bloquear tu área de ataque, incluyendo ataques a distancia y conjuros.

Los aliados y los enemigos inmovilizados no afectarán a tus ataques de área ni a las bonificaciones.</s>]]}


