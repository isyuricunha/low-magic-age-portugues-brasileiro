<h3 c=ty>1. Combate por Turnos</h3>
Cuando comienza el combate, todos los personajes comienzan sus turnos según una secuencia de pruebas de iniciativa. Después de que un personaje termine todas sus acciones, su turno termina y comienza el del siguiente. Cuando todos los combatientes terminan su turno, la ronda termina y el combatiente más rápido vuelve a actuar. Se repiten estos pasos hasta el final del combate, que es cuando uno de los grupos de combatientes han perdido toda capacidad de combate.


<h3 c=ty>2. Actúa con estrategia</h3>
Un personaje puede realizar dos acciones por turno: una <c=y>Acción Estándar</c> y una <c=g>Acción de Movimiento</c>. Atacar o lanzar un conjuro suelen ser acciones estándar, mientras que acciones más simples como moverse o cambiar armas son acciones de movimiento.

Una técnica típica de combate consiste en moverse a una casilla adyacente a un enemigo y atacarle. Si ya estás en una casilla adyacente al enemigo, puedes quedarte ahí (o usar Paso, ver más abajo) y realizar tu <c=y>Ataque de turno Completo</c>. Tal ataque consumirá ambas acciones, tanto la estándar como la de movimiento, pero es más poderoso.


<h3 c=ty>3. ¡Ten cuidado con los <c=r>Ataques de Oportunidad</c> de los enemigos!</h3>
Es peligroso distraerse con otras cosas y bajar la guardia en medio de un combate. Los oponentes cercanos aprovecharán tu debilidad ¡y darán un golpe demoledor! Ese tipo de ataques gratuitos provocados se denominan <c=r>Ataques de Oportunidad</c>.

Algunas acciones provocarán ataques de oportunidad, tales como moverse, los ataques a distancia o el lanzamiento de conjuros.

Piénsatelo dos veces antes de dispararle a un enemigo adyacente o si te alejas de él. Usar <c=g>Paso</c> de forma correcta podría ayudar a alejarte de forma segura.


Adelante, busca más técnicas de combate por ti mismo entre sangre y acero...]]


