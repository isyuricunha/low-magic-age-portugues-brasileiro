<h3>O talento "Two-Weapon Rending" funciona com duas bestas de mão?</h3>
Não. "Two-Weapon Defense", "Improved Two-Weapon Defense", "Double Slice" e "Two-Weapon Rend" só funcionam com empunhadura dupla corpo a corpo.


<h3>Como fazer uma investida?</h3>
Uma investida é ativada automaticamente quando todos os pré-requisitos são atendidos: antes de um ataque corpo a corpo, realizou um movimento em linha reta a partir de ao menos 2 casas de distância, com todo o caminho livre de obstáculos e terreno difícil.


<h3>Encantamento: Defending (Apenas armas)</h3>
Em armas corpo a corpo pode haver um encantamento especial: Defending - +x bônus de escudo na classe de armadura, funciona de forma semelhante a um escudo equipado.

Esse bônus não se acumula com o bônus de classe de armadura de um escudo real, portanto é mais adequado para personagens com armas de duas mãos ou empunhadura dupla e sem escudo.

Fica um pouco mais complicado quando o encantamento Defending ocorre em armas que são tanto corpo a corpo quanto arremessáveis, como uma lança: o encantamento funciona normalmente quando a arma é usada como corpo a corpo; mas não tem efeito se a arma for usada para arremesso.


<h3>Virar morto dos clérigos:</h3>
Teste de virar: nível do personagem + modificador de Carisma + bônus de talento vs. defesa de Vontade do alvo + Resistência ao virar


<h3>Às vezes não há efeito ao conjurar uma magia que tem alvo fora da visão.</h3>
Conjurar uma magia requer linha de efeito. Se houver obstáculos invisíveis bloqueando a linha de efeito, a magia simplesmente falha.


<h3>Como os obstáculos, inimigos e aliados afetam o campo de batalha?</h3>

Influências no movimento:

Obstáculos e inimigos não restritos bloquearão seu movimento. Você não pode atravessar.

Casas adjacentes a inimigos não restritos são sua <c=r>Zona de Controle (ZoC)</c>, e você não pode atravessar. Você deve primeiro mover-se para tal casa e parar, então esperar seu próximo turno para continuar movendo.

Inimigos não restritos empunhando armas corpo a corpo atacarão qualquer oponente que tente sair de sua ZoC, esse ataque é chamado <c=r>Opportunity Attack (OA)</c>. Mudar de posição usando <c=g>Shift</c> (passo de 1 casa) pode prevenir OAs.

Terreno difícil: terreno com pequenos obstáculos ou alguns efeitos de magia (Teia, Graxa, etc.), e casas ocupadas por seus aliados ou inimigos restritos são considerados terreno difícil. Esses terrenos exigem o dobro de esforço para atravessar, e <c=g>Shift</c> não é permitido neles.


Influências no ataque:

Obstáculos e inimigos não restritos podem afetar seus ataques se o alvo estiver sob <c=r>Cobertura</c> (ataque <c=r>-2</c>) ou <c=r>Cobertura Superior</c> (ataque <c=r>-4</c>); eles também podem bloquear sua área de ataque, incluindo ataques à distância e magias.

