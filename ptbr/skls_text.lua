s_skls_use="Usando Habilidades"
s_skls_use_d=[[
<s b=c:ty>Quando seu personagem usa uma habilidade, você faz um teste de habilidade para ver quão bem ele ou ela executa.

Quanto maior o resultado do teste de habilidade, melhor.

Com base nas circunstâncias, seu resultado deve igualar ou superar um número específico (uma CD ou o resultado de um teste de habilidade oposto) para que o teste seja bem-sucedido.

Quanto mais difícil a tarefa, maior o número que você precisa rolar.

As circunstâncias podem afetar seu teste.

Um personagem que está livre de distrações pode fazer uma tentativa cuidadosa e evitar erros simples.

Um personagem que tem muito tempo pode tentar várias vezes, garantindo o melhor resultado.

Se outros ajudarem, o personagem pode ter sucesso onde de outra forma falharia.


<b>Testes de Habilidade: </b>Um teste de habilidade leva em conta o treinamento do personagem (rank da habilidade), talento natural (modificador de característica) e sorte (o dado).

Ele também pode levar em conta a aptidão racial do personagem para certas coisas (bônus racial) ou a penalidade de verificação de armadura que ele ou ela está usando, ou um certo feito que o personagem possui, entre outras coisas.

Para fazer um teste de habilidade, role 1d20 e adicione o modificador da habilidade do seu personagem para essa habilidade.

O modificador da habilidade incorpora os ranks do personagem nessa habilidade e o modificador da característica chave da habilidade, além de quaisquer outros modificadores diversos que possam ser aplicados, incluindo bônus raciais e penalidades de verificação de armadura.

Quanto maior o resultado, melhor.

Ao contrário de testes de ataque e de resistência, um rolar natural de 20 no d20 não é um sucesso automático, e um rolar natural de 1 não é uma falha automática.


<b>Classe de Dificuldade: </b>Alguns testes são feitos contra uma Classe de Dificuldade (CD).

A CD é um número (definido usando as regras de habilidades como diretriz) que você deve alcançar como resultado no seu teste de habilidade para ter sucesso.


