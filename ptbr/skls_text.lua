Você sabe como usar as ferramentas do seu ofício, como executar as tarefas diárias do artesanato, como supervisionar ajudantes não treinados e como lidar com problemas comuns. (Trabalhadores e assistentes não treinados ganham em média 1 peça de prata por dia.)

A função básica da habilidade de Artesanato, porém, é permitir que você crie um item do tipo apropriado.

A CD depende da complexidade do item a ser criado.

A CD, seus resultados de teste e o preço do item determinam quanto tempo leva para fazer um item específico.

O preço final do item também determina o custo das matérias-primas.

Em alguns casos, o feitiço fabricar pode ser usado para alcançar os resultados de um teste de Artesanato sem um teste real.

Entretanto, você deve fazer um teste de Artesanato apropriado ao usar o feitiço para criar artigos que exigem um alto grau de habilidade.

Um teste de Artesanato bem-sucedido relacionado à carpintaria em conjunto com o lançamento do feitiço madeira de ferro permite que você faça itens de madeira que têm a força do aço.

Ao lançar o feitiço criação menor, você deve ter sucesso em um teste de Artesanato apropriado para fazer um item complexo.

Todos os artesanatos requerem ferramentas de artesão para dar a melhor chance de sucesso.

Se ferramentas improvisadas forem usadas, o teste é feito com penalidade de circunstância -2.

Por outro lado, ferramentas de artesão de obra-prima concedem +2 de bônus de circunstância no teste.

Para determinar quanto tempo e dinheiro leva para fazer um item, siga estes passos.

1. Encontre o preço do item. Coloque o preço em peças de prata (1 po = 10 pp).

2. Encontre a CD na tabela abaixo.

3. Pague um terço do preço do item para o custo das matérias-primas.

4. Faça um teste de Artesanato apropriado representando uma semana de trabalho.

Se o teste for bem-sucedido, multiplique seu resultado de teste pela CD.

Se o resultado × a CD for igual ao preço do item em pp, então você completou o item.

Se o resultado × a CD for o dobro ou triplo do preço do item em peças de prata, então você completou a tarefa em metade ou um terço do tempo.

Outros múltiplos da CD reduzem o tempo da mesma forma.

Se o resultado × a CD não for igual ao preço, então ele representa o progresso que você fez nesta semana. Registre o resultado e faça um novo teste de Artesanato para a próxima semana. Cada semana, você faz mais progresso até que o total alcance o preço do item em peças de prata.

Se você falhar um teste por 4 ou menos, não faz progresso nesta semana.

Se você falhar por 5 ou mais, você estraga metade das matérias-primas e tem que pagar metade do custo original das matérias-primas novamente.


<b c=ty7>Progress by the Day: </b>Progresso por Dia: Você pode fazer testes por dia ao invés de por semana.

Neste caso seu progresso (resultado do teste × CD) está em peças de cobre ao invés de peças de prata.


<b c=ty7>Creating Masterwork Items: </b>Criando Itens de Obra-Prima: Você pode fazer um item de obra-prima - uma arma, conjunto de armadura, escudo ou ferramenta que concede um bônus em seu uso através de sua excepcional habilidade, não por ser mágico.

Para criar um item de obra-prima, você cria o componente de obra-prima como se fosse um item separado além do item padrão.

O componente de obra-prima tem seu próprio preço (300 po para uma arma ou 150 po para um conjunto de armadura ou escudo) e uma CD de Artesanato de 20.

Uma vez que ambos os componentes padrão e de obra-prima estejam concluídos, o item de obra-prima está finalizado.

Nota: O custo que você paga pelo componente de obra-prima é um terço do valor dado, assim como é para o custo das matérias-primas.


<b c=ty7>Repairing Items: </b>Reparando Itens: Geralmente, você pode reparar um item fazendo testes contra a mesma CD que foi necessária para fazer o item inicialmente.

O custo de reparar um item é um quinto do preço do item.


