<h2 c=ty>武器型別</h2>
按照不同的規則，武器被劃分成幾個型別，這些規則包括了熟練使用武器時必須掌握的技巧（簡易武器，軍用武器，異種武器）；在近戰中使用的（近戰武器）或者是遠距離使用（遠端，包括投擲武器和彈射武器）； 武器的持用方式（輕武器，單手武器，雙手武器），以及武器的尺寸（小型，中型，大型）。


<c=ty b>簡易，軍用，異種武器：</c><z>除了德魯伊，武僧，盜賊和法師之外的所有職業都擅長使用所有的簡易武器。野蠻人，戰士，聖騎士和巡林客可以擅長使用所有的簡易武器和軍用武器。而其他</z>大多數職業的人物能掌握主要的簡易武器，可能還會包括一些軍用武器，甚至異種武器。如果你使用不擅長的武器，攻擊檢定將會有-4的減值。


<c=ty b>近戰武器和遠端武器：</c>近戰武器主要是用來進行近身攻擊，不過有些武器也可以投擲。遠端武器包括投擲和彈射武器，它們在近戰中沒什麼威力。

<c=ty>長型武器：</c>大砍刀，長勾刀，長槍，長矛，刺叉，刺鏈和鞭子屬於長型武器，長型武器的使用者可以攻擊並不在臨近區域內的目標。大多數長型武器可以讓使用者的威脅範圍加倍，這意味著典型的小型或者中型生物在使用長型武器時可以攻擊到10英尺遠的目標<z>，但不能用它來攻擊臨近區域內的目標。一個典型的大型生物在使用長型武器時可以攻擊到15到20英尺遠的目標，但不能它來攻擊距離在10英尺內的目標</z>。

<c=ty>雙頭武器：</c>雙頭鏈枷，矮人矛斧，侏儒鉤式戰錘，獸人雙頭斧，木棍和雙頭劍屬於雙頭武器，使用者可以使用雙頭武器的兩端同時戰鬥，就像使用雙武器戰鬥一樣，但同時也會受到使用雙武器戰鬥的減值，視為一把單手武器和一把輕武器。

