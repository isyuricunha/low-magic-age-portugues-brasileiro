<s b=c:ty><b>核心规则：</b>每当你试图进行一个有一定几率失败的动作时，你投一个20面骰子（d20）。

为了检测你的人物是否成功完成动作，你必须：
• 投d20。
• 加上任何相关的修正值。
• 拿结果与目标数值进行比较。

如果结果等于或大于目标数值，你的人物成功。

若小于目标数值，那么你失败了。


<b>骰子（DICE）：</b>投骰子是用类似“3d4+3”的公式来描述的，它表示“投了3个四面骰并加3”（结果是6至15间的一个数）。

第一个数字告诉你投几个骰子（把它们的结果加起来）。

紧跟在“d”后面的数字告诉你使用的骰子类型。

后面任何的数字表明结果中将要加上或减去的数值。


<b>d%：</b>百分骰的使用略有区别。

你通过投两个不同的10面骰子产生一个1至100之间的数。

其中一个骰子（在投之前决定）是十位数，另一个是个位数。

两个0代表100。


<b>小数的舍入：</b>通常情况下，当你得到小数时要去掉小数部分，即使小数部分等于或大于0.5也是如此。

<b c=tw>特例：</b>某些特定的投骰最小为1，比如伤害和生命值。


<b>乘法：</b>有时候规则让你乘一个数或一个投出的值。


当只有一个乘数时，正常地乘那个数即可。


而当有两个或多个乘数乘以任何抽象值（比如修正或投出的值）时，将这些乘数合并成一个单独的乘数，即每个额外的乘数减一后加到第一个乘数上。

因此，一个2倍（×2）再加一个 2倍（×2）得到的是3倍（×3，因为 2 + 1 = 3）。


当乘数是现实中的值（比如重量或距离），替换以不同的乘法规则。

一个生物双倍其体型（因此其重量乘8），然后被石化（它的重量大约要乘上一个因子3），此时的重量是平时的24倍而不是10倍。

相似的，一个瞎了的生物试图通过困难的地形，每个方格将按4个方格计算（两次翻倍，总共是×4），而不是相当于3个方格（加上两次100%）。
