<s b=c:ty><b>La meccanica di base:</b> Ogni volta che si tenta un'azione che ha qualche possibilità di fallimento, si tira un dado a venti facce (d20).

Per determinare se il tuo personaggio ha successo in un compito fai così:
- Tira un d20.
- Aggiungi eventuali modificatori rilevanti.
- Confronta il risultato con un numero obiettivo.

Se il risultato è uguale o superiore al numero obiettivo, il tuo personaggio ha successo.

Se il risultato è inferiore al numero obiettivo, fallisce.


<b>I dadi:</b> I lanci dei dadi sono descritti con espressioni come “3d4+3”, che significa “lanciare tre dadi a quattro facce e aggiungere 3” (ottenendo un numero tra 6 e 15).

Il primo numero dice quanti dadi lanciare (sommando i risultati).

Il numero immediatamente dopo la “d” ti dice il tipo di dado da usare.

Qualsiasi numero successivo indica una quantità che viene aggiunta o sottratta dal risultato.


<b>d%:</b> I dadi percentuali funzionano un po' diversamente.

Si genera un numero tra 1 e 100 lanciando due diversi dadi a dieci facce.

Uno (designato prima del lancio) è la cifra delle decine. L'altro è la cifra dell'uno.

Due 0 rappresentano 100.


<b>Ragioni di arrotondamento:</b> In generale, se ti ritrovi con una frazione, arrotonda per difetto, anche se la frazione è la metà o più grande.

<b c=tw>Eccezione:</b> Alcuni tiri, come i danni e i punti ferita, hanno un minimo di 1.


<b>Moltiplicare:</b> A volte una regola ti fa moltiplicare un numero o un tiro di dado.


Finché si applica un solo moltiplicatore, si moltiplica il numero normalmente.


Quando due o più moltiplicatori si applicano a qualsiasi valore astratto (come un modificatore o un tiro di dado), tuttavia, li combina in un singolo multiplo, con ogni multiplo extra che aggiunge 1 in meno del suo valore al primo multiplo.

Così, un doppio (×2) e un doppio (×2) applicati allo stesso numero risultano in un triplo (×3, perché 2 + 1 = 3).


Quando si applicano moltiplicatori a valori del mondo reale (come il peso o la distanza), si applicano invece le normali regole della matematica.

Una creatura la cui taglia raddoppia (moltiplicando così il suo peso per 8) e poi viene trasformata in pietra (il che moltiplicherebbe il suo peso per un fattore di circa 3) ora pesa circa 24 volte il normale, non 10 volte il normale.

Allo stesso modo, una creatura accecata che tenta di attraversare un terreno difficile conterebbe ogni casella come 4 caselle (raddoppiando il valore due volte, per un moltiplicatore totale di ×4), piuttosto che come 3 caselle (aggiungendo il 100% due volte).
]]


