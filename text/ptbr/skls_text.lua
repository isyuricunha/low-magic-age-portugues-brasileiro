<s b=c:ty>Para uma classe específica de um personagem, as perícias são divididas em perícias de classe e perícias fora de classe.

Perícias de classe são as perícias presentes na lista de perícias de classe do seu personagem; perícias fora de classe são as que não estão na lista.

Se você adquirir uma perícia de classe, recebe 1 nível (equivalente a um bônus de +1 nos testes com essa perícia) por ponto de perícia.

Se você adquirir uma perícia fora de classe, recebe 1/2 nível por ponto de perícia. (Metade de nível não melhora seu teste de perícia, mas dois meios níveis equivalem a 1 nível.)

Você não pode guardar pontos de perícia para gastar depois.

Seu nível máximo em uma perícia de classe é o nível do seu personagem + 3.

Seu nível máximo em uma perícia fora de classe é a metade desse número (não arredonde para cima ou para baixo).

Independentemente de a perícia ser comprada como perícia de classe ou fora de classe, se ela for uma perícia de classe para qualquer das suas classes, seu nível máximo equivale ao nível total do seu personagem + 3.


<b>Usando Perícias: </b>Para fazer um teste de perícia, role: 1d20 + modificador de perícia.

Modificador de perícia = nível da perícia + modificador de habilidade + modificadores diversos.

Essa rolagem funciona como uma rolagem de ataque ou um teste de resistência - quanto maior a rolagem, melhor.

Você pode estar tentando igualar ou superar uma certa Classe de Dificuldade (CD), ou tentando superar o resultado do teste de outro personagem.


<b>Níveis de Perícia: </b>O número de níveis de um personagem em uma perícia depende de quantos pontos de perícia ele investiu nessa perícia.

Muitas perícias podem ser usadas mesmo que o personagem não tenha níveis nelas; isso é chamado de fazer um teste de perícia não treinada.


<b>Modificador de Habilidade: </b>O modificador de habilidade usado em um teste de perícia é o modificador da habilidade chave da perícia (a habilidade associada ao uso da perícia).

A habilidade chave de cada perícia está anotada em sua descrição.


<b>Modificadores Diversos: </b>Modificadores diversos incluem bônus raciais, penalidades de teste de armadura e bônus concedidos por talentos, entre outros.
