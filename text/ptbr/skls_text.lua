s_skls_use="Usando Perícias"
s_skls_use_d=[[
<s b=c:ty>Quando seu personagem usa uma perícia, você faz um teste de perícia para ver quão bem ele ou ela se sai.

Quanto maior o resultado do teste de perícia, melhor.

Com base nas circunstâncias, seu resultado deve igualar ou superar um número específico (uma CD ou o resultado de um teste de perícia oposto) para que o teste seja bem-sucedido.

Quanto mais difícil a tarefa, maior o número que você precisa rolar.

As circunstâncias podem afetar seu teste.

Um personagem que pode trabalhar sem distrações pode fazer uma tentativa cuidadosa e evitar erros simples.

Um personagem que tem muito tempo pode tentar repetidamente, garantindo o melhor resultado.

Se outros ajudarem, o personagem pode ter sucesso onde de outra forma falharia.


<b>Testes de Perícia: </b>Um teste de perícia leva em conta o treinamento do personagem (rank da perícia), talento natural (modificador de habilidade) e sorte (a rolagem do dado).

Também pode considerar a aptidão da sua raça para certas coisas (bônus racial) ou a armadura que ele ou ela está usando (penalidade de teste de armadura), ou um determinado talento que o personagem possui, entre outras coisas.

Para fazer um teste de perícia, role 1d20 e adicione o modificador de perícia do seu personagem para essa perícia.

O modificador de perícia incorpora os ranks do personagem nessa perícia e o modificador de habilidade da habilidade chave da perícia, além de quaisquer outros modificadores diversos que possam se aplicar, incluindo bônus raciais e penalidades de teste de armadura.

Quanto maior o resultado, melhor.

Ao contrário de rolagens de ataque e testes de resistência, um resultado natural 20 no d20 não é um sucesso automático, e um resultado natural 1 não é uma falha automática.


<b>Classe de Dificuldade: </b>Alguns testes são feitos contra uma Classe de Dificuldade (CD).

A CD é um número (definido usando as regras de perícia como diretriz) que você deve alcançar como resultado no seu teste de perícia para ter sucesso.


