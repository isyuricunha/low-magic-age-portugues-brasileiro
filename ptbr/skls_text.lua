s_skls_use_d=[[
<s b=c:ty>Quando seu personagem usa uma habilidade, você faz uma verificação de habilidade para ver quão bem ele ou ela se saiu.

Quanto maior o resultado da verificação de habilidade, melhor.

Baseado nas circunstâncias, seu resultado deve igualar ou superar um número específico (uma CD ou o resultado de uma verificação de habilidade oposta) para que a verificação seja bem-sucedida.

Quanto mais difícil a tarefa, maior o número que você precisa obter.

As circunstâncias podem afetar sua verificação.

Um personagem que está livre para trabalhar sem distrações pode fazer uma tentativa cuidadosa e evitar erros simples.

Um personagem que tem muito tempo pode tentar repetidamente, garantindo assim o melhor resultado.

Se outros ajudarem, o personagem pode ter sucesso onde, de outra forma, falharia.


<b>Verificações de Habilidade: </b>Uma verificação de habilidade leva em consideração o treinamento do personagem (nível de habilidade), talento natural (modificador de habilidade) e sorte (o lançamento de dado).

Ela também pode levar em consideração a aptidão de sua raça para fazer certas coisas (bônus racial) ou que tipo de armadura ele ou ela está vestindo (penalidade de armadura), ou um certo talento que o personagem possui, entre outras coisas.

Para fazer uma verificação de habilidade, jogue 1d20 e adicione o modificador de habilidade do seu personagem para aquela habilidade.

O modificador de habilidade incorpora os níveis do personagem naquela habilidade e o modificador de habilidade para a habilidade-chave daquela habilidade, além de quaisquer outros modificadores diversos que possam se aplicar, incluindo bônus raciais e penalidades de armadura.

Quanto maior o resultado, melhor.

Diferente de jogadas de ataque e testes de resistência, um lançamento natural de 20 no d20 não é um sucesso automático, e um lançamento natural de 1 não é uma falha automática.


<b>Classe de Dificuldade: </b>Algumas verificações são feitas contra uma Classe de Dificuldade (CD).

A CD é um número (definido usando as regras de habilidade como guia) que você deve igualar ou superar no resultado de sua verificação de habilidade para ter sucesso.


