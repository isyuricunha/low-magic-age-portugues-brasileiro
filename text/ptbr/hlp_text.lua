<s b=c:ty><b>Mecânica Central:</b> Sempre que você tenta uma ação que tem alguma chance de falhar, você rola um dado de vinte faces (d20).

 Para determinar se seu personagem tem sucesso em uma tarefa, faça o seguinte:
• Role um d20.
• Some quaisquer modificadores relevantes.
• Compare o resultado a um número-alvo.

 Se o resultado for igual ou superior ao número-alvo, seu personagem tem sucesso.

 Se o resultado for menor que o número-alvo, você falha.


<b>Dados:</b> Rolagens de dados são descritas com expressões como "3d4+3", que significa "role três dados de quatro faces e adicione 3" (resultando em um número entre 6 e 15).

 O primeiro número indica quantos dados rolar (somando os resultados).

 O número imediatamente após o "d" indica o tipo de dado a ser usado.

 Qualquer número após isso indica uma quantidade que será adicionada ou subtraída do resultado.


<b>d%:</b> Dados percentuais funcionam um pouco diferente.

 Você gera um número entre 1 e 100 rolando dois dados de dez faces diferentes.

 Um (designado antes de rolar) representa a dezena. O outro representa a unidade.

 Dois zeros representam 100.


<b>Reações de Arredondamento:</b> Em geral, se o resultado for uma fração, arredonde para baixo, mesmo que a fração seja um meio ou maior.

<b c=tw>Exceção:</b> Algumas rolagens, como dano e pontos de vida, têm um mínimo de 1.


<b>Multiplicação:</b> Às vezes uma regra faz você multiplicar um número ou uma rolagem de dado.


 Enquanto você estiver aplicando um único multiplicador, multiplique o número normalmente.


 Quando dois ou mais multiplicadores se aplicam a qualquer valor abstrato (como um modificador ou uma rolagem de dado), combine-os em um único múltiplo, com cada múltiplo extra adicionando 1 a menos que seu valor ao primeiro múltiplo.

 Assim, um duplo (×2) e outro duplo (×2) aplicados ao mesmo número resultam em um triplo (×3, pois 2 + 1 = 3).


 Ao aplicar multiplicadores a valores do mundo real (como peso ou distância), as regras normais da matemática se aplicam.

 Uma criatura cujo tamanho dobra (multiplicando seu peso por 8) e depois é transformada em pedra (o que multiplicaria seu peso por aproximadamente 3) agora pesa cerca de 24 vezes o normal, não 10 vezes.

 Da mesma forma, uma criatura cega tentando atravessar terreno difícil contaria cada quadrado como 4 quadrados (dobrando o custo duas vezes, totalizando um multiplicador de ×4), ao invés de 3 quadrados (adicionando 100% duas vezes).
