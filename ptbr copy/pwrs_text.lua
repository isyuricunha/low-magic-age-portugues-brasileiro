-- Abbreviate long feat names for Western Europe languages (English, French, Italiano...), no need for Chinese and Japanese
function	abbr_pwrs(t)
	for k, v in pairs(t) do
		mk_abbr(v, "Weapon Proficiency", "WP")
		mk_abbr(v, "Shield Proficiency", "SP")
		mk_abbr(v, "Armor Proficiency", "AP")
		mk_abbr(v, "Two--Bladed", "TB")-- must 2 '-'
		mk_abbr(v, "Double Axe", "D-Axe")
		mk_abbr(v, "Gnome Hooked Hammer", "Gnm. M. Gancho")
		mk_abbr(v, "Two--Weapon", "TA")
		mk_abbr(v, "Two--Handed Weapon", "MA")
		mk_abbr(v, "Combat Maneuvers", "MC")
		mk_abbr(v, "Skill Focus", "FO")
		mk_abbr(v, "Dwarven", "Anão.")
		mk_abbr(v, "Proficiency", "Prof.")
		mk_abbr(v, "Specialization", "Espec.")
		mk_abbr(v, "Critical", "Crítico.")
		mk_abbr(v, "Equipment", "Equip.")
		mk_abbr(v, "Wondrous", "Marav.")

		mk_abbr(v, "Improved ", "Melh. ")
		mk_abbr(v, "Greater ", "Sup. ")
		mk_abbr(v, "Perfect ", "Perf. ")

	--	print(v.a)
	end
end

