-- Abbreviate long feat names for Western Europe languages (English, French, Italiano...), no need for Chinese and Japanese
function	abbr_pwrs(t)
	for k, v in pairs(t) do
		mk_abbr(v, "Competenza nelle armi", "C.Armi")
		mk_abbr(v, "Competenza negli scudi", "C.Scud.")
		mk_abbr(v, "Competenza armature", "C.Armat.")
		mk_abbr(v, "A due lame", "DL")-- must 2 '-'
		mk_abbr(v, "Doppia Ascia", "DA")
		mk_abbr(v, "Martello-picca Gnomesco", "M-P Gnom.")
		mk_abbr(v, "due armi", "2A")-- Combattimento con due armi -> Combattimento con 2A
		mk_abbr(v, "Arma a due mani", "2M")
		mk_abbr(v, "armi a due mani", "2M")
		mk_abbr(v, "Manovre di combattimento", "MC")
		mk_abbr(v, "Abilità Focalizzata", "AF")

		mk_abbr(v, "Nano", "Nno.")
		mk_abbr(v, "Competenza", "Comp.")
		mk_abbr(v, "Specializzazione", "Spec.")
		mk_abbr(v, "Critico", "Crit.")
		mk_abbr(v, "Equipaggiamento", "Equip.")
		mk_abbr(v, "Meraviglioso", "Merav.")

		mk_abbr(v, "Migliorato ", "Migl. ")
		mk_abbr(v, "Superiore ", "Sup.. ")
		mk_abbr(v, "Perfetto ", "Perf. ")

	--	print(v.a)
	end
end

