		mk_abbr(v, "Maîtrise des armes", "MDA")
		mk_abbr(v, "Maîtrise d'arme", "MA")
		mk_abbr(v, "Maîtrise du Bouclier", "MB")
		mk_abbr(v, "Maîtrise des Cuirasse", "MC")
		mk_abbr(v, "Deux--Lâmes", "DL")-- must 2 '-'
		mk_abbr(v, "Double Hache", "D-Hache")
		mk_abbr(v, "Marteau crochu de gnome", "Gnm. Marteau-C")
		mk_abbr(v, "Deux-Armes", "DA")
		mk_abbr(v, "Deux Mains Armées", "DM")
		mk_abbr(v, "Maneuvres de Combat", "MC")
		mk_abbr(v, "Focalisation sur la compétence", "FC")

--		mk_abbr(v, "Nain", "Nain")
		mk_abbr(v, "Maîtrise", "Maît.")
		mk_abbr(v, "Spécialisation", "Spec.")
		mk_abbr(v, "Critique", "Crit.")
		mk_abbr(v, "Equipement", "Eqpt.")
		mk_abbr(v, "Merveilleux", "Merv.")

		mk_abbr(v, "Amélioré(e) ", "Amé. ")
		mk_abbr(v, "Supèrieur(e) ", "Sup. ")
		mk_abbr(v, "Parfait(e) ", "Pft. ")

	--	print(v.a)
	end
end

