[[<b> </b>

<h2 c=ty>攻击检定</h2>
攻击检定决定你的攻击是否击中对手。当你进行攻击检定时，掷d20再加上攻击加值。如果计算结果等于或大于目标的防御，便击中目标，并且对他造成伤害。

<b>必然失手和必然命中：</b>若攻击检定掷出1，不论计算结果为何，都算失手；若掷出20则都算命中。


<h2 c=ty>攻击加值</h2>
近战武器的攻击加值 = 等级调整值 + 力量调整值 + 体型调整值
远程武器的攻击加值 = 等级调整值 + 敏捷调整值 + 体型调整值

<b c=ty>等级调整值：</b>角色的等级反映其综合实力，影响方方面面，包括攻击检定。

<b c=ty>力量调整值：</b>力量对武器攻击的速度和力道都有帮助，所以力量调整值会影响近战攻击检定。

<b c=ty>敏捷调整值：</b>敏捷代表协调性和稳定度，所以敏捷调整值会影响远程武器检定。

<b c=ty>体型调整值：</b>体型大小是相对的。例如，对于半身人而言，人类是较大的目标；而对于食人魔而言，人类是较小的目标。当两个体型相同的生物对战时，他们的体型调整值相互抵销而忽略不计。



<h2 c=ty>防御等级</h2>
你的防御等级（即物理防御值，简称AC）表示对手要击中你有多困难。也就是说，对手的攻击检定结果必须大于等于你的防御等级，才能击中你。

AC = 10 + 等级调整值 + 盔甲加值 + 盾牌加值 + 敏捷调整值 + 其他调整值

<b c=ty>基础AC：</b>AC的基础值为10。

<b c=ty>等级调整值：</b>角色的等级反映其综合实力，影响方方面面，包括防御等级。

<b c=ty>盔甲和盾牌加值：</b>盔甲和盾牌都会对AC提供加值，这代表它们能抵抗攻击的防护程度。

<b c=ty>敏捷调整值：</b>高敏捷值可以帮助你灵活地躲避敌人的攻击。反之，如果敏捷值太低，就常常会因为身手笨拙而被击中。所以敏捷调整值会影响AC。

注意：盔甲会限制敏捷加值。穿着盔甲时，可能无法将敏捷加值完全加在AC上。

某些特殊情况下，你会失去AC上的敏捷加值，比如昏迷。因为敏捷加值是表示你能灵巧地闪躲攻击，所以如果你当时完全无法对攻击做出反应，那么自然就无法将敏捷加值计算到AC上。当然，如果你本来就没有敏捷加值，那就没有影响。

<b c=ty>其他调整值：</b>其他会影响AC的因素，包括：

<b>增强加值：</b>魔法防具有更好的防护力（如+1鳞甲、+2轻盾等）。

<b>偏斜加值：</b>有些魔法偏斜效果可以弹开攻击，增加你的AC。

<b>天生防御加值：</b>天生防御可以增加AC（一般生物种族都没有天生防御，只有某些长有鳞片、毛皮或肌肉特别强壮的生物，才有天生防御加值）。

<b>闪避加值：</b>有些AC加值是因为角色的特殊能力使其可以主动避开攻击，这些加值都称为闪避加值。当失去敏捷加值时，也会失去闪避加值，但穿着盔甲不会限制闪避加值的上限。和其他加值不同的是，闪避加值可以累计。

<b>体型调整值：</b>体型差异会在AC上获得加值或减值。在战斗中，体型较大的生物比较容易被击中，而体型较小的生物则比较不容易被击中。



<h2 c=ty>伤害值</h2>
当你成功击中目标时，就会造成伤害，降低目标当前生命值。伤害值取决于你使用的武器。


<b c=ty>力量调整值：</b>角色的力量调整值可能为正的加值，也可能为负的减值。

当使用近战武器或投掷武器（包括投石索）时，伤害值要加上力量调整值（无论正负）。

当使用普通弓而非复合弓时，伤害值只会受到力量减值，无法受到力量加值。

<b>副手武器：</b>副手持用的武器的伤害值只能加上力量加值的一半。

<b>双手武器：</b>双手持用的武器的伤害值可加上力量加值的1.5倍，轻型武器除外。


<b c=ty>重击伤害：</b>有时你会造成重击（俗称暴击），此时可做多次伤害掷骰（每次加上所有调整值），然后将结果加起来，作为最终伤害值。

<b>例外：</b>以额外骰数表示的伤害加值（如：偷袭、特殊能力或火焰剑的额外伤害），不会因为重击伤害而增加。


<b>示例：</b>一个力量18的角色装备长剑和盾牌时，伤害值有+4加值；装备巨斧时有+6加值；装备两把匕首时，副手只有+2加值。

巨斧的重击倍数是3倍，当造成重击时，可掷3次1d12+6（即3d12+18）。]]}


