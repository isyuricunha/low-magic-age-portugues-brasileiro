<s b=c:ty><b>La Mecánica Básica:</b> Siempre que intentes una acción que tenga alguna posibilidad de fallar, lanzas un dado de veinte caras (d20).

Para determinar si tu personaje tiene éxito, se hace lo siguiente:
• Tiras un d20.
• Añades cualquier modificador relevante.
• Comparas el resultado con el número objetivo.

Si el resultado iguala o excede el número objetivo, el personaje tiene éxito.

Si el resultado es más bajo que el número objetivo, el personaje falla.


<b>Dados:</b> Las tiradas de dados se describen con expresiones del tipo de “3d4+3,” lo cual significa "tirada de tres dados de cuatro caras y añade 3" (lo cual dará un número entre 6 y 15).

El primer número indica cuántas veces se tirará el dado (los resultados se suman).

El número que sigue a la "d" indica el tipo de dado que se usa.

Cualquier número después de ese indica una cantidad añadida o sustraída del resultado.


<b>d%:</b> Los dados de percentiles funcionan de una forma un poco diferente.

Generas un número entre 1 y 100 lanzando dos dados de diez caras diferentes.

Uno, designado antes de lanzar, es el dígito de las decenas, y el otro, el de las unidades.

Dos 0 representan el 100.


<b>Redondeo de fracciones:</b> En general, si el resultado es una fracción, se redondea hacia abajo, incluso si la fracción es la mitad (un medio) o superior.

<b c=tw>Excepción:</b> Ciertas tiradas, tales como las de daño o las de puntos de golpe, tienen un mínimo de 1.


<b>Multiplicadores:</b> A veces, alguna regla te hace tener que multiplicar un número o una tirada de dados.


Siempre que solo se tenga que aplicar un único multiplicador, se multiplica con normalidad.


Cuando dos o más multiplicadores se aplican a un valor abstracto (como un modificador o una tirada de dados), se combinan en un único multiplicador y cada múltiplo adicional añade 1 menos que su valor al primer múltiplo.

Es decir, un doble (x2) más otro doble (x2) que se aplican al mismo valor resulta en un triple (x3, ya que 2 + 1 = 3).


Cuando se apliquen multiplicadores a valores del mundo-real (como el peso o la distancia), se aplican las reglas matemáticas normales.

Una criatura cuyo tamaño se duplica (multiplicando así su peso por 8) y luego es convertido en piedra (lo cual multiplicaría su peso por un factor de aproximadamente 3), pesaría sobre 24 veces lo normal, no 10 veces lo normal.

De manera similar, una criatura cegada que intenta sortear un terreno difícil, contará cada cosilla como 4 casillas (doblando el coste dos veces, para un multiplicador total de 4), en vez de 3 casillas (añadiendo el 100% dos veces).
]]


