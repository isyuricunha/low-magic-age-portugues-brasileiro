Con il talento "Combattere con due armi migliorato": Nessuna penalità, anche con un'arma non leggera nella mano secondaria (correzione attuale: <c=r>0/0</c>).


<h3>Il talento "Resa con due armi" funziona con le balestre a due mani?</h3>
No, non è così. "Difesa con due armi", "Difesa con due armi milgiorata", " Doppio fendente" e "Resa con due armi" funzionano solo con armi da mischia.


<h3>Come effettuare una carica?</h3>
Una carica è attivata automaticamente quando tutti i prerequisiti sono soddisfatti: prima di un attacco in mischia, fatto un movimento in linea retta da almeno 2 quadretti di distanza, con l'intero percorso libero da ostacoli e da terreno impervio.


<h3>Incantamento: Difesa (solo armi)</h3>
Sulle armi da mischia potrebbe esserci anche un incantamento speciale: Difesa - +x bonus allo scudo sulla CA, funziona un po' come uno scudo equipaggiato.

Questo bonus non si sovrappone al bonus alla CA di uno scudo vero e proprio, quindi è più adatto a personaggi con armi a due mani o due armi ad una mano e senza scudo.

È un po' più complicato quando il potenziamento di difesa si presenta su armi sia da mischia che da lancio, come un giavellotto: il potenziamento funziona normalmente quando l'arma è usata come arma da mischia; ma non ha effetto se l'arma è usata per il lancio.


<h3>Scacciare non morti del chierico:</h3>
Prova di scacciare: livello del personaggio + modificatore di Carisma + bonus ai talenti contro la difesa di Volontà del bersaglio + Resistenza allo scacciamento


<h3>A volte non c'è alcun effetto quando viene lanciato un incantesimo che mira al di fuori della visuale.</h3>
Il lancio di un incantesimo ha bisogno della linea d'effetto. Se ci sono ostacoli invisibili che bloccano la linea d'effetto, l'incantesimo fallirà.


<h3>Come influiscono gli ostacoli, i nemici e gli alleati sul campo di battaglia?</h3>

Influenze sul movimento :

Gli ostacoli e i nemici non immobilizzati bloccheranno il tuo movimento. Non è possibile attraversarli.

Le caselle adiacenti ai nemici non immobilizzati sono le loro <c=r>Zone di Controllo (ZdC)</c>, e non puoi attraversarle. Dovresti prima muoverti in una di queste caselle e fermarti, poi aspettare il prossimo turno per continuare a muoverti.

I nemici non immobilizzati che equipaggiano armi da mischia attaccheranno qualsiasi avversario che cerca di lasciare la loro ZdC, tale attacco è chiamato <c=r>Attacco di Opportunità (AO)</c>. Cambiare posizione usando si usa <c=g>Passo</c> (1 spostamento di una casella) può prevenire gli AO.

Terreno impervio: i terreni con ostacoli minori o alcuni effetti di incantesimi (Ragnatela, Grasso, ecc.), e le caselle occupate dai tuoi alleati o dai nemici immobilizzati sono tutti considerati come terreno impervio. Questi terreni richiedono sforzi doppi per essere attraversati, e non è consentito lo <c=g>spostamento</c> su di essi.


Influenze sugli attacchi:

Gli ostacoli e i nemici non immobilizzati potrebbero influenzare i tuoi attacchi se il bersaglio è sotto <c=r>Copertura</c> (attacco <c=r>-2</c>) o <c=r>Copertura superiore</c> (attacco <c=r>-4</c>); potrebbero anche bloccare la tua area di attacco, inclusi gli attacchi a distanza e gli incantesimi.

Gli alleati e i nemici immobilizzati non influenzeranno la tua area di attacco e i tuoi bonus.</s>]]}


