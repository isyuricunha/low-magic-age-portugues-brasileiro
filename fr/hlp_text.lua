<s h3=c:lbl>
<h3>Détails sur le combat avec deux armes</h3>
Ajustement par défaut (main droite/gauche) : <c=r>-6/-10</c>

Avec le talent "Combat avec deux armes" : <c=g>+2/+6</c> (ajustement actuel : <c=r>-4/-4</c>)

Arme légère dans la main gauche : <c=g>+2/+2</c> (ajustement actuel : <c=r>-2/-2</c>)

Avec le talent "Combat parfait avec deux armes" : aucune pénalité, même avec une arme non légère dans la main gauche (ajustement actuel : <c=r>0/0</c>).


<h3>Est-ce que le talent "Éventration à deux armes" fonctionne avec une arbalète de poing dans chaque main ?</h3>
Non. "Défense à deux armes", "Science de la défense à deux armes", "Double frappe" et "Éventration à deux armes" ne fonctionnent qu'en attaque au corps à corps.


<h3>Comment faire une charge ?</h3>
Une charge est automatiquement activée lorsque toutes les conditions préalables sont réunies : 


<h3>Enchantement : "De défense" (les armes seulement)</h3>
Sur les armes de mêlée, il est possible d'avoir un enchantement spécial : "De défense" - bonus de bouclier de +x sur la classe d'armure, qui fonctionne un peu comme un bouclier équipé.

Ce bonus ne se cumule pas avec le bonus pour la classe d'armure d'un vrai bouclier. C'est pourquoi il convient mieux aux personnages équipés d'une arme à deux mains ou un ambidextre avec une arme dans chaque arme.

C'est un peu plus compliqué lorsque l'enchantement de défense est appliqué sur des armes qui sont à la fois de mêlée et de jet, comme un javelot : l'enchantement fonctionne alors normalement lorsque l'arme est utilisée comme arme de mêlée, mais n'a aucun effet si elle est utilisée pour le lancer.


<h3>Renvoi des morts-vivants par les clercs:</h3>
test de renvoi : niveau du personnage + modificateur de charisme + bonus de talent contre défense mentale de la cible + résistance au renvoi


<h3>Parfois, il n'y a pas d'effet lorsque vous lancez un sort ciblé en dehors du champ de vision.</h3>
Lancer un sort a besoin d'une ligne de vue. S'il y a des obstacles invisibles qui bloquent cette ligne, le sort échouera.


<h3>Comment les obstacles, les ennemis et les alliés affectent-ils le champ de bataille ?</h3>

Influences sur le déplacement :

Il est impossible de passer sur une case occupée par un obstacle ou un ennemi non immobilisé.

Les cases adjacentes à des ennemis non immobilisés appartiennent à leur <c=r>zone de contrôle (ZdC)</c>, et vous ne pourrez pas les traverser.  Vous devez d'abord vous y arrêter, puis au prochain tour, continuer à avancer.

Les ennemis non immobilisés équipés d'une arme de mêlée attaqueront n'importe quel adversaire essayant de quitter leur ZdC. Une telle attaque est appelée <c=r>attaque d'opportunité (AO)</c>. Changer de position en utilisant un <c=g>pas de côté</c> (1 pas d'une case) peut empêcher les attaques d'opportunité.

Terrains difficiles : les terrains avec des obstacles mineurs ou des effets de sort (toile d'araignée, graisse, etc.), et les cases occupées par vos alliés ou ennemis immobilisés sont tous considérés comme des terrains difficiles. Ils demanderont de redoubler d'efforts pour les traverser (chaque case de terrain difficile compte comme 2 cases de déplacement), et un <c=g>pas de côté</c> n'y est pas autorisé.


Influences sur l'attaque :

Les obstacles et les ennemis non immobilisés peuvent affecter vos attaques si la cible est sous <c=r>abri</c> (attaque <c=r>-2</c>) ou sous <c=r>abri total</c> (attaque <c=r>-4</c>) ; ils peuvent aussi bloquer votre zone d'attaque, notamment les attaques et sorts à distance.

Les alliés et les ennemis immobilisés n'ont pas de ZdC.</s>]]}


