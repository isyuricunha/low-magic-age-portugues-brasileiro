<h3 c=ty>1. Combate por Turnos</h3>
Quando o combate começa, todos os personagens iniciam seus turnos seguindo a ordem de seus testes de iniciativa. Após um personagem concluir todas as suas ações, seu turno termina e passa para o próximo. Quando todos os combatentes terminaram seus turnos, um round se encerra e o combatente mais rápido inicia seu turno novamente. Repita esses passos até que o combate termine, o que significa que um grupo de combatentes perdeu todas as suas capacidades de combate.


<h3 c=ty>2. Ações Estratégicas</h3>
Um personagem pode realizar duas ações por turno: uma <c=y>Ação Padrão</c> e uma <c=g>Ação de Movimento</c>. Atacar e lançar uma magia são normalmente ações padrão, enquanto ações mais simples, como mover-se e trocar de arma, são ações de movimento.

Uma técnica de combate típica é mover-se para a casa adjacente a um inimigo e atacá-lo. Se você já estiver adjacente ao inimigo, pode simplesmente permanecer onde está (ou fazer um deslocamento, veja abaixo) e realizar seu <c=y>Ataque de Turno Completo</c>. Esse ataque consome automaticamente tanto sua ação padrão quanto a de movimento e é mais poderoso!


<h3 c=ty>3. Cuidado com <c=r>Ataques de Oportunidade</c> dos inimigos!</h3>
É perigoso se distrair com outras coisas e baixar a guarda durante um combate intenso. Os oponentes próximos mirarão seu ponto fraco e desferirão um golpe devastador! Esse tipo de ataque gratuito desencadeado é chamado de <c=r>Ataques de Oportunidade</c>.

Algumas ações provocam ataques de oportunidade, como mover-se, ataques à distância e lançamento de magias.

Pense duas vezes antes de atirar em um inimigo adjacente ou simplesmente fugir dele. Usar <c=g>Deslocamento</c> adequadamente pode ajudá-lo a recuar com segurança.


Avance, e busque por mais técnicas de combate por conta própria entre sangue e aço...]]


