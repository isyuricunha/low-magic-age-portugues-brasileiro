s_skls_use="Utiliser les compétences"
s_skls_use_d=[[
<s b=c:ty>Lorsque votre personnage utilise une compétence, vous effectuez un test de compétence pour voir à quel point il le fait.

Plus le résultat du test de compétence est élevé, mieux c'est.

Selon les circonstances, votre résultat doit correspondre ou battre un nombre particulier (un DD ou le résultat d'un test de compétence opposé) pour que le test réussisse.

Plus la tâche est difficile, plus le nombre que vous devez obtenir est élevé.

Les circonstances peuvent affecter votre chèque.

Un personnage qui est libre de travailler sans distractions peut faire une tentative prudente et éviter de simples erreurs.

Un personnage qui a beaucoup de temps peut essayer encore et encore, assurant ainsi le meilleur résultat.

Si les autres l'aident, le personnage peut réussir là où sinon il échouerait.


<b>Contrôles de compétence : </b>Un contrôle de compétence prend en compte l'entraînement d'un personnage (rang de compétence), son talent naturel (modificateur de capacité) et sa chance (le jet de dé).

Il peut également tenir compte du talent de sa race pour faire certaines choses (bonus racial) ou de l'armure qu'il porte (malus au test d'armure), ou d'un certain don que possède le personnage, entre autres.

Pour faire un test de compétence, lancez 1d20 et ajoutez le modificateur de compétence de votre personnage pour cette compétence.

Le modificateur de compétence intègre les rangs du personnage dans cette compétence et le modificateur de capacité pour la capacité clé de cette compétence, ainsi que tous les autres modificateurs divers qui peuvent s'appliquer, y compris les bonus raciaux et les pénalités de contrôle d'armure.

Plus le résultat est élevé, mieux c'est.

Contrairement aux jets d'attaque et aux jets de sauvegarde, un jet naturel de 20 au d20 n'est pas un succès automatique, et un jet naturel de 1 n'est pas un échec automatique.


<b>Classe de difficulté : </b>Certaines vérifications sont effectuées par rapport à une classe de difficulté (CD).

Le CD est un nombre (défini en utilisant les règles de compétence comme ligne directrice) que vous devez marquer à la suite de votre test de compétence pour réussir.


