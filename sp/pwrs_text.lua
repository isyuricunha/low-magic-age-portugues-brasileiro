		mk_abbr(v, "Competencia con Escudo", "C. Esc.")
		mk_abbr(v, "Competencia con Armadura", "C. Armad.")
		mk_abbr(v, "Dos Hojas", "DH")-- must 2 '-'
		mk_abbr(v, "Doble Hacha", "D-Hacha")
		mk_abbr(v, "Martillo Ganchudo Gnomo", "M-Gan. Gnomo")
		mk_abbr(v, "Dos Armas", "2A")
		mk_abbr(v, "Arma a dos manos", "2M")
		mk_abbr(v, "Maniobras de Combate", "MC")
		mk_abbr(v, "Soltura con una Habilidad", "SH")

		mk_abbr(v, "Enano", "En.")
		mk_abbr(v, "Competencia", "Comp.")
		mk_abbr(v, "Especialización", "Espec.")
		mk_abbr(v, "Crítico", "Crít.")
		mk_abbr(v, "Equipamiento", "Equip.")
		mk_abbr(v, "Maravilloso", "Marav.")

		mk_abbr(v, "Mejorado ", "Mej. ")
		mk_abbr(v, "Mayor ", "Mayor ")
