<b>Réessayer : </b>En général, vous pouvez réessayer un test de compétence si vous échouez, et vous pouvez continuer indéfiniment.

Certaines compétences ont cependant des conséquences d'échec dont il faut tenir compte.

Quelques compétences sont pratiquement inutiles une fois qu'un contrôle a échoué sur une tentative d'accomplir une tâche particulière.

Pour la plupart des compétences, lorsqu'un personnage a réussi une fois à une tâche donnée, les succès supplémentaires n'ont pas de sens.


<b>Vérifications de compétences non entraînées : </b>Généralement, si votre personnage tente d'utiliser une compétence qu'il ne possède pas, vous effectuez une vérification de compétence comme d'habitude.

Le modificateur de compétence n'a pas de rang de compétence ajouté car le personnage n'a pas de rang dans la compétence.

Tous les autres modificateurs applicables, tels que le modificateur de la capacité clé de la compétence, sont appliqués au test.

De nombreuses compétences ne peuvent être utilisées que par quelqu'un qui y est formé. 


<b>Conditions favorables et défavorables : </b>Certaines situations peuvent rendre une compétence plus facile ou plus difficile à utiliser, entraînant un bonus ou une pénalité au modificateur de compétence pour un test de compétence ou une modification du DD du test de compétence.


Les chances de réussite peuvent être modifiées de quatre manières pour tenir compte de circonstances exceptionnelles.

1. Donnez à l'utilisateur de la compétence un bonus de circonstance de +2 pour représenter les conditions qui améliorent les performances, comme avoir l'outil parfait pour le travail, obtenir l'aide d'un autre personnage (voir Combiner les tentatives de compétence) ou posséder des informations inhabituellement précises.

2. Donnez à l'utilisateur de la compétence une pénalité de circonstance de -2 pour représenter des conditions qui entravent les performances, telles que le fait d'être obligé d'utiliser des outils improvisés ou d'avoir des informations trompeuses.

3. Réduisez le DC de 2 pour représenter les circonstances qui facilitent la tâche, comme avoir un public amical ou faire un travail qui peut être inférieur à la moyenne.

4. Augmentez le DC de 2 pour représenter les circonstances qui rendent la tâche plus difficile, comme le fait d'avoir un public peu coopératif ou de faire un travail qui doit être impeccable.


Les conditions qui affectent la capacité de votre personnage à exécuter la compétence modifient le modificateur de compétence.

Les conditions qui modifient la façon dont le personnage doit exécuter la compétence pour réussir changent le DD.

Un bonus au modificateur de compétence et une réduction du DD du test ont le même résultat : ils créent une meilleure chance de réussite.

Mais ils représentent des circonstances différentes, et parfois cette différence est importante.


<b>Vérifications du temps et des compétences : </b>L'utilisation d'une compétence peut prendre un tour, peu de temps, ou prendre plusieurs tours, voire plus.

La plupart des utilisations des compétences sont des actions standard, des actions de déplacement ou des actions complètes.

Les types d'actions définissent la durée d'exécution des activités dans le cadre d'un round de combat (6 secondes) et la manière dont le mouvement est traité par rapport à l'activité.

Certains tests de compétences sont instantanés et représentent des réactions à un événement, ou sont inclus dans le cadre d'une action. Ces tests de compétence ne sont pas des actions. D'autres tests de compétence représentent une partie du mouvement.


<b>Tests sans jets : </b>Un test de compétence représente une tentative d'atteindre un objectif, généralement sous une sorte de contrainte de temps ou de distraction.

Parfois, cependant, un personnage peut utiliser une compétence dans des conditions plus favorables et éliminer le facteur chance.


<b c=ty7>Prise de 10 : </b>Lorsque votre personnage n'est pas menacé ou distrait, vous pouvez choisir de prendre 10.

Au lieu de lancer 1d20 pour le test de compétence, calculez votre résultat comme si vous aviez obtenu un 10.

Pour de nombreuses tâches de routine, en prendre 10 les rend automatiquement réussies.

Les distractions ou les menaces (comme le combat) empêchent un personnage de prendre 10.

Dans la plupart des cas, faire 10 est purement une mesure de sécurité - vous savez (ou vous attendez) qu'un jet moyen réussira mais craignez qu'un mauvais jet échoue, vous choisissez donc de vous contenter du jet moyen (un 10).

Prendre 10 est particulièrement utile dans les situations où un jet particulièrement élevé n'aiderait pas.


<b c=ty7>Prendre 20 : </b>Lorsque vous avez beaucoup de temps (généralement 2 minutes pour une compétence qui peut normalement être vérifiée en 1 tour, une action complète ou une action simple), vous êtes confronté à aucune menace ou distraction, et la compétence tentée n'entraîne aucune pénalité en cas d'échec, vous pouvez en prendre 20.

En d'autres termes, vous finirez par obtenir un 20 sur 1d20 si vous lancez suffisamment de fois.

Au lieu de lancer 1d20 pour le test de compétence, calculez simplement votre résultat comme si vous aviez obtenu un 20.

Prendre 20 signifie que vous essayez jusqu'à ce que vous ayez raison, et cela suppose que vous échouez plusieurs fois avant de réussir.

Prendre 20 prend vingt fois plus de temps que de faire une seule vérification.

Étant donné que prendre 20 suppose que le personnage échouera plusieurs fois avant de réussir, si vous essayez de prendre 20 sur une compétence qui entraîne des pénalités en cas d'échec, votre personnage subira automatiquement ces pénalités avant de pouvoir terminer la tâche.

Les compétences courantes « prendre 20 » incluent Evasion Artiste, ouverture dévérouillage et Recherche.


<b c=ty7>Contrôles de compétence et de niveau de lanceur de sorts : </b>Les règles normales de prise de 10 et de prise de 20 s'appliquent aux tests de capacité.

Aucune règle ne s'applique aux tests de niveau de lanceur de sorts.


<b>Combiner les tentatives de compétences : </b>Lorsque plusieurs personnages essaient la même compétence en même temps et dans le même but, leurs efforts peuvent se chevaucher.


<b>Événements individuels : </b>Souvent, plusieurs personnages tentent une action et chacun réussit ou échoue indépendamment. Le résultat du test d'Escalade d'un personnage n'influence pas les résultats du test d'Escalade des autres personnages.


<b>Aider un autre : </b>Vous pouvez aider un autre personnage à réussir son test de compétence en effectuant le même type de test de compétence dans le cadre d'un effort de coopération.

Si vous obtenez un 10 ou plus à votre test, le personnage que vous aidez obtient un bonus de +2 à son test, selon la règle des conditions favorables. (Vous ne pouvez pas faire 10 à un test de compétence pour en aider un autre.)

Dans de nombreux cas, l'aide d'un personnage ne sera pas bénéfique, ou seul un nombre limité de personnages peut aider à la fois.

Dans les cas où la compétence restreint qui peut obtenir certains résultats, vous ne pouvez pas aider un autre à accorder un bonus à une tâche que votre personnage ne pourrait pas accomplir seul.


<b>Synergie de compétences : </b>Il est possible pour un personnage d'avoir deux compétences qui fonctionnent bien ensemble.

En général, avoir 5 rangs ou plus dans une compétence donne au personnage un bonus de +2 aux tests de compétence avec chacune de ses compétences synergiques, comme indiqué dans la description de la compétence.

Dans certains cas, ce bonus s'applique uniquement à des utilisations spécifiques de la compétence en question, et pas à tous les tests.

Certaines compétences offrent des avantages sur d'autres tests effectués par un personnage, tels que les tests requis pour utiliser certaines fonctionnalités de classe.


<b>Contrôles d'aptitude : </b>Parfois, un personnage essaie de faire quelque chose auquel aucune compétence spécifique ne s'applique vraiment.

Dans ces cas, vous effectuez un test de caractéristique.

Un test de caractéristique est un jet de 1d20 plus le modificateur de caractéristique approprié.

Essentiellement, vous effectuez un test de compétence sans formation.

Dans certains cas, une action est un test direct de ses capacités sans aucune chance.

Tout comme vous ne feriez pas de test de taille pour voir qui est le plus grand, vous ne faites pas de test de Force pour voir qui est le plus fort.
