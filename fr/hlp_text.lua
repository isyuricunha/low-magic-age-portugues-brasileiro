faq=[[<c=twa>Foire aux questions

<s h3=c:tw>
<h3>Q : Rien ne se passe après avoir modifié la résolution d'écran ?</h3>
R : Veuillez redémarrer le jeu.


<h3>Q : Puis-je choisir les capacités et les talents lors du passage au niveau supérieur ?</h3>
R : Sélectionnez "Personnalisé" lors de la création d'un personnage et gérez-le vous-même. Les personnages "Prédéfinis" sont conçus pour les joueurs novices.


<h3>Q : Quel est le niveau maximum ?</h3>
R : Actuellement, il n'y a pas de limite en mode "Arène" pour les passages au niveau supérieur. Ni pour les niveaux de l'arène.


<h3>Q : Ma barre des compétences est complètement remplie et je ne vois pas les nouvelles compétences.</h3>
R : Faites un clic droit sur la barre des compétences pour remplacer et ajouter de nouvelles compétences.
     Faites un clic droit sur le personnage pour sélectionner toutes ses compétences disponibles.


<h3>Q : Comment puis-je consulter la séquence d'action et autres informations des combattants ?</h3>
R : Appuyez sur la touche <b>Alt</b> pour voir la "<b>séquence d'action</b>" et autres informations.


<h3>Q : Puis-je utiliser des portraits personnalisés et d'autres ressources ?</h3>
R : Toutes les ressources du jeu sont ouvertes et vous pouvez les modifier/remplacer librement.
   dossier "gfx" : les graphismes
   dossier "sfx" : la musique et les effets sonores
   dossier "text" : les textes.

Vous pouvez également télécharger d'autres ressources directement depuis <url=http://steamcommunity.com/app/576770/workshop/>Steam Workshop</url>.


<h3>Q : Pourquoi ne pas recharger une arbalète ? Cela introduit un déséquilibre qui fait que les arbalètes lourdes deviennent meilleures que les arcs longs, tant en portée qu'en dégâts.</h3>
R : Bonne suggestion. Le fait est que cliquer pour recharger est ennuyeux, et que la multiplication des avertissements d'une attaque d'opportunité est encore pire. C'est pourquoi l'action de rechargement est supprimée avec le talent "Rechargement rapide".

Il y aura plus de talents pour faire la différence entre les arcs et les arbalètes dans une future version : les arcs sont meilleurs pour le tir rapide et les cibles multiples, et les arbalètes pour les dégâts plus importants et les attaques perforantes.


<h3>Q : Pourquoi les lance-pierres sont-ils des armes à deux mains ? Ce sont des armes traditionnellement à une main.</h3>
R : Oui, ce sont des armes à une main, mais il faut deux mains pour les recharger. Il suffit d'avoir une arbalète de poing comme arme à distance à une main.


<h3>Q : Pourquoi ne pas courir, feinter, aider les autres, etc. Le jeu serait beaucoup plus intéressant !</h3>
R : Oui, ça viendra. Pour le moment, nous mettons l'accent sur le combat simple ne présentant aucune difficulté. Nous travaillons sur une série d'actions compliquées comme le système des manœuvres de combat de Pathfinder et d'autres options seront ajoutées progressivement.

Rajouter davantage d'options n'est pas toujours la meilleure solution, car elles peuvent engendrer des ralentissements dans le déroulement d'un combat. Dans ADnD TRPG, une telle situation se produit, même sans qu'il y ait trop d'options. Voici un exemple bien RÉEL :

   Le combattant : "Dois-je le renverser ou le repousser ?"
   Le roublard : "Ne le repousse pas. J'ai besoin de le prendre en tenaille."
   Le clerc : "C'est risqué. Avec un seul pas de côté, nous serons tous dans son aura !"
   Le roublard : "Fais un pas en arrière. Je vais lui porter un coup en permutant de position."
   Le magicien : "Ou alors, je peux le tirer plus près."
   Le combattant : "Non, tu ne pourras pas. C'est un angle difficile."
   Le magicien : "Je peux me déplacer jusque là et le tirer. Mais le clerc ne devrait pas être sur ma trajectoire."
   Le clerc : "Si je recule, le roublard sera frappé."
   
   Dix minutes plus tard, ils finissent par trouver la meilleure tactique. Le combattant lance son dé avec assurance. Le résultat est un ÉCHEC.

   "Il est temps de reconsidérer..."
   
     - Posté par Sheepy, administrateur du forum TRPG www.goddessfantasy.net.
</s></c>]]


