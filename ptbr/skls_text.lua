<s b=c:ty>Para uma classe específica de um personagem, as habilidades são divididas em habilidades de classe e habilidades fora de classe.

Habilidades de classe são as habilidades encontradas na lista de habilidades de classe do seu personagem; habilidades fora de classe são aquelas que não aparecem na lista.

Se você comprar uma habilidade de classe, recebe 1 rank (equivalente a um bônus de +1 nos testes com essa habilidade) por ponto de habilidade.

Se você comprar uma habilidade fora de classe, recebe 1/2 rank por ponto de habilidade. (Ranks meio não melhoram seu teste de habilidade, mas dois ranks meio equivalem a 1 rank.)

Você não pode guardar pontos de habilidade para gastar depois.

Seu rank máximo em uma habilidade de classe é seu nível de personagem + 3.

Seu rank máximo em uma habilidade fora de classe é a metade desse número (não arredonde para cima ou para baixo).

Independentemente de a habilidade ser comprada como habilidade de classe ou fora de classe, se ela for uma habilidade de classe para qualquer das suas classes, seu rank máximo equivale ao seu nível total de personagem + 3.


<b>Usando Habilidades: </b>Para fazer um teste de habilidade, role: 1d20 + modificador da habilidade.

Modificador da habilidade = rank da habilidade + modificador da característica + modificadores diversos.

Esse teste funciona como um teste de ataque ou um teste de resistência - quanto maior o resultado, melhor.

Você pode estar tentando igualar ou superar uma certa Classe de Dificuldade (CD), ou estar tentando superar o resultado do teste de outro personagem.


<b>Ranks de Habilidade: </b>O número de ranks de um personagem em uma habilidade baseia-se em quantos pontos de habilidade o personagem investiu nessa habilidade.

Muitas habilidades podem ser usadas mesmo que o personagem não tenha ranks nelas; isso é chamado de fazer um teste de habilidade não treinada.


<b>Modificador de Característica: </b>O modificador de característica usado em um teste de habilidade é o modificador da habilidade chave da habilidade (a característica associada ao uso da habilidade).

A habilidade chave de cada habilidade está anotada em sua descrição.


<b>Modificadores Diversos: </b>Modificadores diversos incluem bônus raciais, penalidades de verificação de armadura e bônus fornecidos por feitos, entre outros.
