O preço final do item também determina o custo das matérias-primas.


Em alguns casos, a magia fabricar pode ser usada para obter os resultados de um teste de Artesanato sem um teste real.

Entretanto, você deve fazer um teste de Artesanato apropriado ao usar a magia para criar artigos que exigem alto grau de artesanato.


Um teste de Artesanato bem-sucedido relacionado à carpintaria em conjunto com a magia madeira de ferro permite que você fabrique itens de madeira com a resistência do aço.

Ao lançar a magia criação menor, você deve ter sucesso em um teste de Artesanato apropriado para criar um item complexo.


Todas as artes requerem ferramentas de artesão para oferecer a melhor chance de sucesso.

Se ferramentas improvisadas forem usadas, o teste é feito com penalidade de circunstância -2.

Por outro lado, ferramentas de artesão obra-prima concedem bônus de circunstância +2 no teste.


Para determinar quanto tempo e dinheiro são necessários para fabricar um item, siga estes passos.

1. Descubra o preço do item. Converta o preço para peças de prata (1 po = 10 ps).

2. Encontre a CD na tabela abaixo.

3. Pague um terço do preço do item para o custo das matérias-primas.

4. Faça um teste de Artesanato apropriado representando uma semana de trabalho.

Se o teste for bem-sucedido, multiplique o resultado do teste pela CD.

Se o resultado × a CD for igual ao preço do item em ps, então você completou o item.

Se o resultado × a CD for igual ao dobro ou triplo do preço do item em peças de prata, então você completou a tarefa em metade ou um terço do tempo.

Outros múltiplos da CD reduzem o tempo da mesma forma.

Se o resultado × a CD não for igual ao preço, ele representa o progresso que você fez nesta semana. Registre o resultado e faça um novo teste de Artesanato na semana seguinte. Cada semana, você avança até que o total alcance o preço do item em peças de prata.

Se você falhar no teste por 4 ou menos, não faz nenhum progresso nesta semana.

Se falhar por 5 ou mais, você estraga metade das matérias-primas e precisa pagar novamente metade do custo original das matérias-primas.


<b c=ty7>Progresso por Dia: </b>Você pode fazer testes por dia ao invés de por semana.

Neste caso, seu progresso (resultado do teste × CD) está em peças de cobre ao invés de peças de prata.


<b c=ty7>Criando Itens Obra-Prima: </b>Você pode criar um item obra-prima - uma arma, armadura, escudo ou ferramenta que concede um bônus em seu uso graças ao artesanato excepcional, não por ser mágico.

Para criar um item obra-prima, você cria o componente obra-prima como se fosse um item separado além do item padrão.

O componente obra-prima tem seu próprio preço (300 po para uma arma ou 150 po para uma armadura ou escudo) e uma CD de Artesanato 20.

Quando ambos, o componente padrão e o componente obra-prima, são concluídos, o item obra-prima está finalizado.

Observação: O custo que você paga pelo componente obra-prima é um terço do valor indicado, assim como ocorre com o custo das matérias-primas.


