<h3 c=ty>1. Combattimento a turni</h3>
All' inizio del combattimento, tutti i personaggi cominciano il loro turno seguendo la sequenza dei loro tiri di iniziativa. Dopo che un personaggio ha finito tutte le sue azioni, il suo turno è finito e si passa a quello successivo. Quando tutti i combattenti hanno finito il proprio turno, si conclude un round e il combattente più veloce ricomincia il suo turno. Questi passi si ripetono fino alla fine del combattimento, il che significa che un gruppo di combattenti ha perso tutte le sue capacità di combattimento.


<h3 c=ty>2. Agire con strategia</h3>
Un personaggio può compiere due azioni per turno: un'<c=y>Azione standard</c> e un'<c=g>Azione di movimento</c>. Attaccare e lanciare un incantesimo sono normalmente azioni standard, mentre azioni più semplici come muoversi e cambiare arma sono azioni di movimento.

Una tipica tecnica di combattimento è muoversi in una casella adiacente di un nemico e attaccarlo. Se si è già adiacenti al nemico, si può semplicemente rimanere dove si è (o spostarsi, vedi sotto) e fare il proprio <c=y>Attacco completo</c>. Un attacco di questo tipo consuma automaticamente entrambe le tue azioni standard e di movimento ed è più potente!


<h3 c=ty>4. Attenzione agli <c=r>Attacchi di opportunità</c> dei nemici!</h3>
È pericoloso distrarsi con altre cose e abbassare la guardia durante un feroce combattimento. Gli avversari vicini mireranno al tuo punto debole e sferreranno un colpo micidiale! Questi tipi di attacchi innescati e gratuiti sono chiamati <c=r>Attacchi di opportunità</c>.

Alcune azioni provocano attacchi di opportunità, come muoversi, attaccare a distanza e lanciare incantesimi.

Pensaci due volte prima di sparare a un nemico adiacente o semplicemente fuggire da lui. Utilizzare correttamente <c=g>Passo</c> potrebbe aiutare a fuggire in modo sicuro.


Coraggio, cerca da solo altre tecniche di combattimento tra il sangue e l'acciaio...]]


