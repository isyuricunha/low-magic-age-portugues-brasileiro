<b>驅散不死生物：</b>牧師和較高級別聖武士都有同樣能力。如果人物的聖武士等級達到4級或者更高，那麼他的有效驅散不死生物等級為他的牧師等級加上他的聖武士等級再減3。
<z>
<b>魔寵：</b>法師和術士都有相同能力。法師/術士兼職人物將其法師和術士等級相加來決定魔寵的天生防禦、智力值以及特殊能力。
</z>
