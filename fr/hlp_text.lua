cmt_101=[[<b> </b>

<h3 c=ty>1. Combat au tour par tour</h3>
Quand le combat commence, tous les personnages agissent en suivant l'ordre indiqué par le résultat de leur test d'initiative, du plus élevé au plus faible. Dès qu'un personnage a terminé toutes les actions qui lui sont allouées, son tour se termine et on passe au suivant. Une fois que tout le monde a agi pendant son tour, un nouveau round commence avec celui qui a obtenu la meilleure initiative. Ces étapes se répètent jusqu'à la fin du combat.


<h3 c=ty>2. Agir avec stratégie</h3>
Au cours d'un round ordinaire, un personnage effectue dans la plupart des cas deux actions par tour : une <c=y>action simple</c> et une <c=g>action de mouvement</c>. Attaquer et lancer un sort sont normalement des actions simples, alors que celles comme se déplacer et permuter d'arme sont des actions de mouvement.

Une technique de combat classique consiste à se déplacer dans une case adjacente à un ennemi et à l'attaquer. Si vous êtes déjà au contact de l'ennemi, vous pouvez rester où vous êtes et effectuer une <c=y>action complexe</c>. Une telle attaque consommera automatiquement votre action simple et votre action de mouvement, mais elle sera plus puissante !


<h3 c=ty>3. Méfiez-vous des <c=r>attaques d'opportunité</c> de vos ennemis !</h3>
Il est dangereux d'être distrait par d'autres choses et de baisser la garde lors d'un combat acharné. Les adversaires proches viseront votre point faible et porteront un coup écrasant! Ce type d'attaques gratuites déclenchées est appelé <c=r>Attaques d'opportunité</c>.

Certaines actions provoqueront des attaques d'opportunité, telles que le déplacement, l'attaque à distance et le lancement de sorts.

Réfléchissez à deux fois avant de tirer sur un ennemi adjacent ou juste de l'évacuer. Utiliser à bon escient <c=g>Pas de côté</c> pourrait vous aider à vous retirer en toute sécurité.


Allez-y et cherchez plus de techniques de combat par vous-même parmi le sang et l'acier ...]]


